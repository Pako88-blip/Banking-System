
package banking.database;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public final class DatabaseInitializer {

    private DatabaseInitializer() {
    }

    public static void initialize() throws SQLException {

        String customersTable = """
            CREATE TABLE IF NOT EXISTS CUSTOMERS (
                CUSTOMER_ID VARCHAR(20) PRIMARY KEY,
                FIRST_NAME VARCHAR(60) NOT NULL,
                LAST_NAME VARCHAR(60) NOT NULL,
                PHONE_NUMBER VARCHAR(30),
                EMAIL VARCHAR(120) NOT NULL UNIQUE,
                PASSWORD_HASH VARCHAR(255) NOT NULL,
                PASSWORD_SALT VARCHAR(255) NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """;

        String accountsTable = """
            CREATE TABLE IF NOT EXISTS ACCOUNTS (
                ACCOUNT_NUMBER VARCHAR(30) PRIMARY KEY,
                CUSTOMER_ID VARCHAR(20) NOT NULL,
                ACCOUNT_TYPE VARCHAR(20) NOT NULL,
                BALANCE DECIMAL(15,2) NOT NULL DEFAULT 0.00,
                INITIAL_DEPOSIT DECIMAL(15,2) NOT NULL,
                IS_EMPLOYED BOOLEAN NOT NULL DEFAULT FALSE,
                EMPLOYER_NAME VARCHAR(120),
                EMPLOYER_ADDRESS VARCHAR(255),
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                CONSTRAINT FK_ACCOUNT_CUSTOMER
                    FOREIGN KEY (CUSTOMER_ID)
                    REFERENCES CUSTOMERS(CUSTOMER_ID),

                CONSTRAINT CK_ACCOUNT_TYPE
                    CHECK (ACCOUNT_TYPE IN (
                        'SAVINGS', 'INVESTMENT', 'CHEQUE'
                    )),

                CONSTRAINT CK_ACCOUNT_BALANCE
                    CHECK (BALANCE >= 0),

                CONSTRAINT CK_INITIAL_DEPOSIT
                    CHECK (
                        INITIAL_DEPOSIT >= 0
                        AND (
                            ACCOUNT_TYPE <> 'INVESTMENT'
                            OR INITIAL_DEPOSIT >= 500
                        )
                    ),

                CONSTRAINT CK_CHEQUE_EMPLOYMENT
                    CHECK (
                        ACCOUNT_TYPE <> 'CHEQUE'
                        OR (
                            IS_EMPLOYED = TRUE
                            AND EMPLOYER_NAME IS NOT NULL
                            AND EMPLOYER_ADDRESS IS NOT NULL
                        )
                    )
            )
            """;

        String transactionsTable = """
            CREATE TABLE IF NOT EXISTS TRANSACTIONS (
                TRANSACTION_ID BIGINT
                    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ACCOUNT_NUMBER VARCHAR(30) NOT NULL,
                TRANSACTION_TYPE VARCHAR(20) NOT NULL,
                AMOUNT DECIMAL(15,2) NOT NULL,
                TRANSACTION_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                BALANCE_AFTER DECIMAL(15,2) NOT NULL,

                CONSTRAINT FK_TRANSACTION_ACCOUNT
                    FOREIGN KEY (ACCOUNT_NUMBER)
                    REFERENCES ACCOUNTS(ACCOUNT_NUMBER),

                CONSTRAINT CK_TRANSACTION_TYPE
                    CHECK (TRANSACTION_TYPE IN (
                        'DEPOSIT', 'WITHDRAWAL', 'INTEREST'
                    )),

                CONSTRAINT CK_TRANSACTION_AMOUNT
                    CHECK (AMOUNT > 0),

                CONSTRAINT CK_TRANSACTION_BALANCE
                    CHECK (BALANCE_AFTER >= 0)
            )
            """;

        try (
            Connection connection = DatabaseConnection.getConnection();
            Statement statement = connection.createStatement()
        ) {

            statement.execute(customersTable);
            statement.execute(accountsTable);
            statement.execute(transactionsTable);

            System.out.println("Database schema initialized successfully.");

        }
    }
}
